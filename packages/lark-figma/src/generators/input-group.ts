/**
 * InputGroup Component Generator
 *
 * Generates an InputGroup ComponentSet in Figma.
 *
 * An InputGroup joins an input with optional addons and buttons inside a
 * single bordered container. Feishu draws the group with a 1px component
 * border that turns brand-coloured on hover/focus — there is no focus halo.
 *
 * @see packages/lark/src/components/input-group/input-group.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindFillToVariable,
  bindStrokeToVariable,
  bindTextColorToVariable,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  SPACING,
  VAR_NAMES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { createIconInstance, bindIconColor } from "./icon-utils";
import { logComplete } from "../logger";

// Import variant data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

const inputGroup = registry.components.InputGroup;
const sizeProp = inputGroup.props.size as {
  values: string[];
  classes: Record<string, string>;
  descriptions: Record<string, string>;
  default: string;
};

/**
 * Container classes of the InputGroup zone.
 * The group shares a single 1px component border with its children.
 */
const CONTAINER_CLASSES =
  "flex min-w-0 flex-1 items-center gap-0 overflow-hidden rounded-md border border-lark-border px-0";

/**
 * The input inside the group keeps the Input component's horizontal padding
 * (`pl-[11px] pr-2`) and typography.
 */
const INPUT_CLASSES = "pl-[11px] pr-2 text-base";

/**
 * Addon glyph — Feishu draws prefix/suffix icons with `--icon-n2`.
 */
const ADDON_CLASSES = "flex shrink-0 items-center gap-1.5 text-lark-subtle";

/** Addon icon size */
const ADDON_ICON_SIZE = 16;

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get size configuration from registry
 */
export function getInputGroupSizeConfig() {
  return {
    values: sizeProp.values,
    classes: sizeProp.classes,
    descriptions: sizeProp.descriptions,
    default: sizeProp.default,
  };
}

/**
 * Get parsed container styles
 */
export function getInputGroupParsedContainerStyles() {
  return parseTailwindClasses(CONTAINER_CLASSES);
}

/**
 * Get parsed styles for a specific size
 */
export function getInputGroupParsedSizeStyles(size: string) {
  const classes = sizeProp.classes[size] || "";
  return {
    size,
    classes,
    description: sizeProp.descriptions[size] || "",
    parsed: parseTailwindClasses(classes),
  };
}

/**
 * Get all size data (for snapshot testing)
 */
export function getAllInputGroupVariantData() {
  const containerStyles = getInputGroupParsedContainerStyles();
  const inputStyles = parseTailwindClasses(INPUT_CLASSES);
  const addonStyles = parseTailwindClasses(ADDON_CLASSES);
  const config = getInputGroupSizeConfig();

  return {
    container: {
      raw: CONTAINER_CLASSES,
      parsed: containerStyles,
    },
    input: {
      raw: INPUT_CLASSES,
      parsed: inputStyles,
    },
    addon: {
      raw: ADDON_CLASSES,
      parsed: addonStyles,
    },
    sizes: config.values.map((size) => {
      const sizeData = getInputGroupParsedSizeStyles(size);
      return {
        ...sizeData,
        layout: {
          layoutMode: "HORIZONTAL",
          primaryAxisAlignItems: "CENTER",
          counterAxisAlignItems: "CENTER",
          itemSpacing: containerStyles.gap ?? 0,
          height: sizeData.parsed.height ?? 32,
          cornerRadius: containerStyles.borderRadius ?? BORDER_RADIUS.md,
          paddingLeft: inputStyles.paddingLeft ?? 11,
          paddingRight: inputStyles.paddingRight ?? 8,
          fontSize: sizeData.parsed.fontSize ?? FONT_SIZE.base,
        },
      };
    }),
  };
}

/**
 * Create a single InputGroup component
 */
async function createInputGroupComponent(size: string): Promise<ComponentNode> {
  const containerStyles = getInputGroupParsedContainerStyles();
  const inputStyles = parseTailwindClasses(INPUT_CLASSES);
  const addonStyles = parseTailwindClasses(ADDON_CLASSES);
  const sizeStyles = getInputGroupParsedSizeStyles(size).parsed;

  const component = figma.createComponent();
  component.name = "size=" + size;
  component.description = sizeProp.descriptions[size] || "";

  component.layoutMode = "HORIZONTAL";
  component.primaryAxisAlignItems = "CENTER";
  component.counterAxisAlignItems = "CENTER";
  component.primaryAxisSizingMode = "FIXED";
  component.counterAxisSizingMode = "FIXED";
  component.itemSpacing = containerStyles.gap ?? 0;
  component.paddingLeft = 0;
  component.paddingRight = 0;
  component.paddingTop = 0;
  component.paddingBottom = 0;
  component.cornerRadius = containerStyles.borderRadius ?? BORDER_RADIUS.md;
  component.resize(280, sizeStyles.height ?? 32);

  // The group sits on the page background
  const bgVar = getVariableByName(VAR_NAMES.color.base);
  if (bgVar) {
    bindFillToVariable(component, bgVar.id);
  }

  // Feishu outlines the group with the component border colour
  const borderVar = getVariableByName(VAR_NAMES.color.border);
  if (borderVar) {
    bindStrokeToVariable(component, borderVar.id, 1);
  }

  // Leading addon
  const addon = figma.createFrame();
  addon.name = "Addon";
  addon.layoutMode = "HORIZONTAL";
  addon.primaryAxisAlignItems = "CENTER";
  addon.counterAxisAlignItems = "CENTER";
  addon.primaryAxisSizingMode = "AUTO";
  addon.counterAxisSizingMode = "AUTO";
  addon.itemSpacing = addonStyles.gap ?? SPACING.base;
  addon.paddingLeft = SPACING.base;
  addon.paddingRight = 0;
  addon.fills = [];

  const addonIcon = createIconInstance("ph-magnifying-glass", ADDON_ICON_SIZE);
  if (addonIcon) {
    addonIcon.name = "Addon Icon";
    if (addonStyles.textVariable) {
      bindIconColor(addonIcon, addonStyles.textVariable);
    }
    addon.appendChild(addonIcon);
  }
  component.appendChild(addon);

  // Input text
  const inputText = await createTextNode(
    "Search…",
    sizeStyles.fontSize ?? FONT_SIZE.base,
    FALLBACK_VALUES.fontWeight.normal,
  );
  inputText.name = "Input";
  inputText.paddingLeft = inputStyles.paddingLeft ?? 11;
  inputText.paddingRight = inputStyles.paddingRight ?? 8;
  const placeholderVar = getVariableByName(VAR_NAMES.text.placeholder);
  if (placeholderVar) {
    bindTextColorToVariable(inputText, placeholderVar.id);
  }
  component.appendChild(inputText);

  return component;
}

/**
 * Generate InputGroup ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateInputGroupComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getInputGroupSizeConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  let currentY = 0;
  for (const size of config.values) {
    const component = await createInputGroupComponent(size);
    rowLabels.push({ y: currentY, text: "size=" + size });
    component.x = 160;
    component.y = currentY;
    currentY += component.height + 48;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "InputGroup";
  componentSet.description = "Input with addons and buttons in one border";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "InputGroup",
      startY,
      rowLabels,
      labelColumnWidth: 160,
    },
  );

  logComplete(
    "Generated InputGroup ComponentSet with " +
      components.length +
      " sizes (light + dark)",
  );

  return nextY;
}
