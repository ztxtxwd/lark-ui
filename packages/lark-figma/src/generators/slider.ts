/**
 * Slider Component Generator
 *
 * Generates a Slider ComponentSet in Figma.
 *
 * A Feishu slider is a label, a rail (`bg-lark-line`), a filled indicator
 * (`bg-lark-brand`) and a round thumb with a 1px outline. The rail height
 * comes from the size variant, the thumb size from the size styles.
 *
 * @see packages/lark/src/components/slider/slider.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindFillToVariable,
  bindStrokeToVariable,
  bindTextColorToVariable,
  createShadowEffects,
  LARK_SHADOWS,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  SPACING,
  VAR_NAMES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { logComplete } from "../logger";

// Import variant data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

const sliderComponent = registry.components.Slider;
const sizeProp = sliderComponent.props.size as {
  values: string[];
  classes: Record<string, string>;
  descriptions: Record<string, string>;
  default: string;
};

/**
 * Root classes of the Slider (flex w-full flex-col gap-2)
 */
const BASE_CLASSES = "flex w-full flex-col gap-2";

/**
 * Rail classes (relative h-1 w-full rounded-xs bg-lark-line)
 */
const TRACK_CLASSES = "relative h-1 w-full rounded-xs bg-lark-line";

/**
 * Filled part of the rail (h-full rounded-xs bg-lark-brand)
 */
const INDICATOR_CLASSES = "h-full rounded-xs bg-lark-brand";

/**
 * Thumb size per slider size (SLIDER_SIZE_STYLES in slider.tsx)
 */
const THUMB_SIZE_CLASSES: Record<string, string> = {
  sm: "h-3 w-3",
  base: "h-4 w-4",
};

/** Sample value shown in the tooltip bubble */
const SAMPLE_VALUE = "50";

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get size configuration from registry
 */
export function getSliderSizeConfig() {
  return {
    values: sizeProp.values,
    classes: sizeProp.classes,
    descriptions: sizeProp.descriptions,
    default: sizeProp.default,
  };
}

/**
 * Get parsed base styles
 */
export function getSliderParsedBaseStyles() {
  return parseTailwindClasses(BASE_CLASSES);
}

/**
 * Get parsed styles for a specific size
 */
export function getSliderParsedSizeStyles(size: string) {
  const classes = sizeProp.classes[size] || "";
  return {
    size,
    classes,
    description: sizeProp.descriptions[size] || "",
    parsed: parseTailwindClasses(classes),
    thumb: parseTailwindClasses(THUMB_SIZE_CLASSES[size] || ""),
  };
}

/**
 * Get all size data (for snapshot testing)
 */
export function getAllSliderVariantData() {
  const baseStyles = getSliderParsedBaseStyles();
  const trackStyles = parseTailwindClasses(TRACK_CLASSES);
  const indicatorStyles = parseTailwindClasses(INDICATOR_CLASSES);
  const config = getSliderSizeConfig();

  return {
    baseStyles: {
      raw: BASE_CLASSES,
      parsed: baseStyles,
    },
    track: {
      raw: TRACK_CLASSES,
      parsed: trackStyles,
    },
    indicator: {
      raw: INDICATOR_CLASSES,
      parsed: indicatorStyles,
    },
    sizes: config.values.map((size) => {
      const sizeData = getSliderParsedSizeStyles(size);
      return {
        ...sizeData,
        layout: {
          layoutMode: "VERTICAL",
          itemSpacing: baseStyles.gap ?? SPACING.base,
          railHeight: sizeData.parsed.height ?? 24,
          thumbSize: sizeData.thumb.width ?? 12,
          primaryAxisSizingMode: "AUTO",
          counterAxisSizingMode: "FIXED",
        },
      };
    }),
  };
}

/**
 * Create a single Slider component
 */
async function createSliderComponent(size: string): Promise<ComponentNode> {
  const baseStyles = getSliderParsedBaseStyles();
  const sizeStyles = getSliderParsedSizeStyles(size);
  const trackStyles = parseTailwindClasses(TRACK_CLASSES);
  const indicatorStyles = parseTailwindClasses(INDICATOR_CLASSES);

  const component = figma.createComponent();
  component.name = "size=" + size;
  component.description = sizeProp.descriptions[size] || "";

  component.layoutMode = "VERTICAL";
  component.primaryAxisAlignItems = "MIN";
  component.counterAxisAlignItems = "MIN";
  component.primaryAxisSizingMode = "AUTO";
  component.counterAxisSizingMode = "FIXED";
  component.itemSpacing = baseStyles.gap ?? SPACING.base;
  component.fills = [];

  // Label
  const label = await createTextNode(
    "Match count",
    FONT_SIZE.base,
    FALLBACK_VALUES.fontWeight.medium,
  );
  label.name = "Label";
  const labelVar = getVariableByName(VAR_NAMES.text.default);
  if (labelVar) {
    bindTextColorToVariable(label, labelVar.id);
  }
  component.appendChild(label);

  // Rail wrapper (height comes from the size variant)
  const rail = figma.createFrame();
  rail.name = "Rail";
  rail.layoutMode = "HORIZONTAL";
  rail.primaryAxisAlignItems = "CENTER";
  rail.counterAxisAlignItems = "CENTER";
  rail.primaryAxisSizingMode = "FIXED";
  rail.counterAxisSizingMode = "FIXED";
  rail.resize(240, sizeStyles.parsed.height ?? 24);
  rail.fills = [];
  component.appendChild(rail);

  // Track
  const track = figma.createFrame();
  track.name = "Track";
  track.layoutMode = "HORIZONTAL";
  track.primaryAxisAlignItems = "MIN";
  track.counterAxisAlignItems = "CENTER";
  track.primaryAxisSizingMode = "FIXED";
  track.counterAxisSizingMode = "FIXED";
  track.resize(240, trackStyles.height ?? 4);
  track.cornerRadius = trackStyles.borderRadius ?? BORDER_RADIUS.xs;
  if (trackStyles.fillVariable) {
    const trackVar = getVariableByName(trackStyles.fillVariable);
    if (trackVar) {
      bindFillToVariable(track, trackVar.id);
    }
  }
  rail.appendChild(track);

  // Filled indicator (50% of the rail)
  const indicator = figma.createFrame();
  indicator.name = "Indicator";
  indicator.resize(120, indicatorStyles.height ?? trackStyles.height ?? 4);
  indicator.cornerRadius = indicatorStyles.borderRadius ?? BORDER_RADIUS.xs;
  if (indicatorStyles.fillVariable) {
    const indicatorVar = getVariableByName(indicatorStyles.fillVariable);
    if (indicatorVar) {
      bindFillToVariable(indicator, indicatorVar.id);
    }
  }
  track.appendChild(indicator);

  // Thumb — a white circle with a 1px component border
  const thumb = figma.createEllipse();
  thumb.name = "Thumb";
  const thumbSize = sizeStyles.thumb.width ?? 12;
  thumb.resize(thumbSize, thumbSize);
  const thumbBg = getVariableByName(VAR_NAMES.color.elevated);
  if (thumbBg) {
    bindFillToVariable(thumb, thumbBg.id);
  }
  const thumbRing = getVariableByName(VAR_NAMES.color.border);
  if (thumbRing) {
    bindStrokeToVariable(thumb, thumbRing.id, 1);
  }
  thumb.effects = createShadowEffects(LARK_SHADOWS.sm);
  thumb.x = 120 - thumbSize / 2;
  track.appendChild(thumb);

  // Min / max labels
  const range = figma.createFrame();
  range.name = "Range";
  range.layoutMode = "HORIZONTAL";
  range.primaryAxisAlignItems = "SPACE_BETWEEN";
  range.counterAxisAlignItems = "CENTER";
  range.primaryAxisSizingMode = "FIXED";
  range.counterAxisSizingMode = "AUTO";
  range.resize(240, 20);
  range.fills = [];

  const rangeVar = getVariableByName(VAR_NAMES.text.subtle);
  for (const value of ["0", SAMPLE_VALUE]) {
    const rangeText = await createTextNode(
      value,
      FONT_SIZE.base,
      FALLBACK_VALUES.fontWeight.normal,
    );
    rangeText.name = "Range Value";
    if (rangeVar) {
      bindTextColorToVariable(rangeText, rangeVar.id);
    }
    range.appendChild(rangeText);
  }
  component.appendChild(range);

  return component;
}

/**
 * Generate Slider ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateSliderComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getSliderSizeConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  let currentY = 0;
  for (const size of config.values) {
    const component = await createSliderComponent(size);
    rowLabels.push({ y: currentY, text: "size=" + size });
    component.x = 160;
    component.y = currentY;
    currentY += component.height + 48;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "Slider";
  componentSet.description = "Range slider with a Feishu rail and thumb";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "Slider",
      startY,
      rowLabels,
      labelColumnWidth: 160,
    },
  );

  logComplete(
    "Generated Slider ComponentSet with " +
      components.length +
      " sizes (light + dark)",
  );

  return nextY;
}
