/**
 * InlineCopyText Component Generator
 *
 * Generates an InlineCopyText ComponentSet in Figma.
 *
 * InlineCopyText is a borderless inline control that reveals a copy icon on
 * hover/focus. It renders a `Text` child, so the text colours come from the
 * Text component's registry entry and the container comes from the
 * InlineCopyText styling metadata.
 *
 * @see packages/lark/src/components/inline-copy-text/inline-copy-text.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindTextColorToVariable,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  SPACING,
  GRID_LAYOUT,
  VAR_NAMES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { createIconInstance, bindIconColor } from "./icon-utils";
import { logComplete } from "../logger";

// Import variant data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

const inlineCopyText = registry.components
  .InlineCopyText as typeof registry.components.InlineCopyText & {
  styling?: { baseClasses?: string };
};

const variantProp = inlineCopyText.props.variant as {
  values: string[];
  descriptions?: Record<string, string>;
  default?: string;
};

/**
 * The InlineCopyText text variants are `Text` variants — read their classes
 * from the Text component's registry entry.
 */
const textVariantProp = registry.components.Text.props.variant as {
  values: string[];
  classes: Record<string, string>;
  descriptions: Record<string, string>;
  default: string;
};

/**
 * Base classes shared by every InlineCopyText (from LARK_INLINE_COPY_TEXT_STYLING)
 */
const BASE_CLASSES =
  inlineCopyText.styling?.baseClasses ||
  "group/inline-copy flex min-w-0 max-w-full cursor-pointer items-center gap-1 rounded-xs border-0 bg-transparent p-0 focus:outline-none focus-visible:outline-none";

/** Copy icon size — the component renders a 14px copy glyph */
const ICON_SIZE = 14;

/**
 * The monospace variants default to the `lg` text size, every other variant
 * defaults to `base` (see inline-copy-text.tsx).
 */
const MONO_VARIANTS = ["mono", "mono-secondary"];

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get variant configuration from registry
 */
export function getInlineCopyTextVariantConfig() {
  return {
    values: variantProp.values,
    classes: textVariantProp.classes,
    descriptions: variantProp.descriptions ?? {},
    default: variantProp.default ?? textVariantProp.default,
  };
}

/**
 * Get parsed base styles
 */
export function getInlineCopyTextParsedBaseStyles() {
  return parseTailwindClasses(BASE_CLASSES);
}

/**
 * Get parsed styles for a specific variant
 */
export function getInlineCopyTextParsedVariantStyles(variant: string) {
  const classes = textVariantProp.classes[variant] || "";
  return {
    variant,
    classes,
    description: textVariantProp.descriptions[variant] || "",
    parsed: parseTailwindClasses(classes),
  };
}

/**
 * Get all variant data (for snapshot testing)
 */
export function getAllInlineCopyTextVariantData() {
  const baseStyles = getInlineCopyTextParsedBaseStyles();
  const config = getInlineCopyTextVariantConfig();

  return {
    baseStyles: {
      raw: BASE_CLASSES,
      parsed: baseStyles,
    },
    variants: config.values.map((variant) => {
      const variantData = getInlineCopyTextParsedVariantStyles(variant);
      const isMono = MONO_VARIANTS.indexOf(variant) !== -1;
      return {
        ...variantData,
        layout: {
          layoutMode: "HORIZONTAL",
          primaryAxisAlignItems: "CENTER",
          counterAxisAlignItems: "CENTER",
          itemSpacing: baseStyles.gap ?? SPACING.xs,
          cornerRadius: baseStyles.borderRadius ?? BORDER_RADIUS.xs,
          primaryAxisSizingMode: "AUTO",
          counterAxisSizingMode: "AUTO",
        },
        text: {
          fontSize: isMono ? FONT_SIZE.lg : FONT_SIZE.base,
          fontWeight:
            variantData.parsed.fontWeight ?? FALLBACK_VALUES.fontWeight.normal,
        },
        icon: {
          iconId: "ph-copy",
          iconSize: ICON_SIZE,
        },
      };
    }),
  };
}

/**
 * Create a single InlineCopyText component
 */
async function createInlineCopyTextComponent(
  variant: string,
): Promise<ComponentNode> {
  const baseStyles = getInlineCopyTextParsedBaseStyles();
  const variantStyles = getInlineCopyTextParsedVariantStyles(variant).parsed;
  const description = textVariantProp.descriptions[variant] || "";

  const component = figma.createComponent();
  component.name = "variant=" + variant;
  component.description = description;

  component.layoutMode = "HORIZONTAL";
  component.primaryAxisAlignItems = "CENTER";
  component.counterAxisAlignItems = "CENTER";
  component.primaryAxisSizingMode = "AUTO";
  component.counterAxisSizingMode = "AUTO";
  component.itemSpacing = baseStyles.gap ?? SPACING.xs;
  component.cornerRadius = baseStyles.borderRadius ?? BORDER_RADIUS.xs;
  // The control is borderless — `border-0` in the base classes
  component.fills = [];

  // Text label
  const isMono = MONO_VARIANTS.indexOf(variant) !== -1;
  const textNode = await createTextNode(
    "0c239dd2",
    isMono ? FONT_SIZE.lg : FONT_SIZE.base,
    variantStyles.fontWeight ?? FALLBACK_VALUES.fontWeight.normal,
  );
  textNode.name = "Label";

  if (variantStyles.textVariable) {
    const textVar = getVariableByName(variantStyles.textVariable);
    if (textVar) {
      bindTextColorToVariable(textNode, textVar.id);
    }
  }
  component.appendChild(textNode);

  // Copy icon (revealed on hover/focus in the React component)
  const icon = createIconInstance("ph-copy", ICON_SIZE);
  if (icon) {
    icon.name = "Copy Icon";
    if (variantStyles.textVariable) {
      bindIconColor(icon, variantStyles.textVariable);
    } else {
      bindIconColor(icon, VAR_NAMES.text.subtle);
    }
    component.appendChild(icon);
  }

  return component;
}

/**
 * Generate InlineCopyText ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateInlineCopyTextComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getInlineCopyTextVariantConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  const labelColumnWidth = GRID_LAYOUT.labelColumnWidth.standard;
  const rowGap = GRID_LAYOUT.rowGap.medium;

  let currentY = 0;
  for (const variant of config.values) {
    const component = await createInlineCopyTextComponent(variant);
    rowLabels.push({ y: currentY, text: "variant=" + variant });
    component.x = labelColumnWidth;
    component.y = currentY;
    currentY += component.height + rowGap;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "InlineCopyText";
  componentSet.description = "Inline copy control for IDs and short values";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "InlineCopyText",
      startY,
      rowLabels,
      labelColumnWidth,
    },
  );

  logComplete(
    "Generated InlineCopyText ComponentSet with " +
      components.length +
      " variants (light + dark)",
  );

  return nextY;
}
