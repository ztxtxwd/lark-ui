/**
 * Toolbar Component Generator
 *
 * Generates a Toolbar ComponentSet in Figma.
 *
 * Feishu groups the toolbar controls into one compact card: a recessed
 * background, a hairline border and a soft elevation. The controls are joined
 * with 1px separators.
 *
 * @see packages/lark/src/components/toolbar/toolbar.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindFillToVariable,
  bindStrokeToVariable,
  bindTextColorToVariable,
  createShadowEffects,
  LARK_SHADOWS,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { logComplete } from "../logger";

// Import variant data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

const toolbarComponent = registry.components.Toolbar;
const sizeProp = toolbarComponent.props.size as {
  values: string[];
  classes: Record<string, string>;
  descriptions: Record<string, string>;
  default: string;
};

/**
 * Root classes of the toolbar card
 * (inline-flex w-fit items-stretch rounded-lg bg-lark-control shadow-lark-xs ring ring-lark-line)
 */
const BASE_CLASSES =
  "inline-flex w-fit items-stretch rounded-lg bg-lark-control shadow-lark-xs ring ring-lark-line";

/**
 * Control classes inside the toolbar
 * (inline-flex h-full items-center gap-2 px-3 text-lark-default)
 */
const CONTROL_CLASSES =
  "inline-flex h-full items-center gap-2 px-3 text-lark-default";

/** Sample control labels */
const SAMPLE_CONTROLS = ["Bold", "Italic", "Link"];

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get size configuration from registry
 */
export function getToolbarSizeConfig() {
  return {
    values: sizeProp.values,
    classes: sizeProp.classes,
    descriptions: sizeProp.descriptions,
    default: sizeProp.default,
  };
}

/**
 * Get parsed base styles
 */
export function getToolbarParsedBaseStyles() {
  return parseTailwindClasses(BASE_CLASSES);
}

/**
 * Get parsed styles for a specific size
 */
export function getToolbarParsedSizeStyles(size: string) {
  const classes = sizeProp.classes[size] || "";
  return {
    size,
    classes,
    description: sizeProp.descriptions[size] || "",
    parsed: parseTailwindClasses(classes),
  };
}

/**
 * Get all size data (for snapshot testing)
 */
export function getAllToolbarVariantData() {
  const baseStyles = getToolbarParsedBaseStyles();
  const controlStyles = parseTailwindClasses(CONTROL_CLASSES);
  const config = getToolbarSizeConfig();

  return {
    baseStyles: {
      raw: BASE_CLASSES,
      parsed: baseStyles,
    },
    control: {
      raw: CONTROL_CLASSES,
      parsed: controlStyles,
    },
    sizes: config.values.map((size) => {
      const sizeData = getToolbarParsedSizeStyles(size);
      return {
        ...sizeData,
        layout: {
          layoutMode: "HORIZONTAL",
          primaryAxisAlignItems: "CENTER",
          counterAxisAlignItems: "CENTER",
          itemSpacing: controlStyles.gap ?? 8,
          paddingLeft: controlStyles.paddingX ?? 12,
          paddingRight: controlStyles.paddingX ?? 12,
          cornerRadius: baseStyles.borderRadius ?? BORDER_RADIUS.lg,
          fontSize: sizeData.parsed.fontSize ?? FONT_SIZE.base,
        },
      };
    }),
  };
}

/**
 * Create a single Toolbar component
 */
async function createToolbarComponent(size: string): Promise<ComponentNode> {
  const baseStyles = getToolbarParsedBaseStyles();
  const controlStyles = parseTailwindClasses(CONTROL_CLASSES);
  const sizeStyles = getToolbarParsedSizeStyles(size).parsed;

  const component = figma.createComponent();
  component.name = "size=" + size;
  component.description = sizeProp.descriptions[size] || "";

  component.layoutMode = "HORIZONTAL";
  component.primaryAxisAlignItems = "CENTER";
  component.counterAxisAlignItems = "CENTER";
  component.primaryAxisSizingMode = "AUTO";
  component.counterAxisSizingMode = "AUTO";
  component.itemSpacing = 0;
  component.paddingLeft = 0;
  component.paddingRight = 0;
  component.paddingTop = 0;
  component.paddingBottom = 0;
  component.cornerRadius = baseStyles.borderRadius ?? BORDER_RADIUS.lg;

  // Recessed toolbar surface
  if (baseStyles.fillVariable) {
    const bgVar = getVariableByName(baseStyles.fillVariable);
    if (bgVar) {
      bindFillToVariable(component, bgVar.id);
    }
  }

  // Hairline border
  if (baseStyles.strokeVariable) {
    const borderVar = getVariableByName(baseStyles.strokeVariable);
    if (borderVar) {
      bindStrokeToVariable(component, borderVar.id, 1);
    }
  }

  // Feishu elevation (shadow-lark-xs)
  component.effects = createShadowEffects(LARK_SHADOWS.xs);

  // Controls
  for (const label of SAMPLE_CONTROLS) {
    const control = figma.createFrame();
    control.name = "Control: " + label;
    control.layoutMode = "HORIZONTAL";
    control.primaryAxisAlignItems = "CENTER";
    control.counterAxisAlignItems = "CENTER";
    control.primaryAxisSizingMode = "AUTO";
    control.counterAxisSizingMode = "AUTO";
    control.itemSpacing = controlStyles.gap ?? 8;
    control.paddingLeft = controlStyles.paddingX ?? 12;
    control.paddingRight = controlStyles.paddingX ?? 12;
    control.paddingTop = 0;
    control.paddingBottom = 0;
    control.fills = [];

    const controlText = await createTextNode(
      label,
      sizeStyles.fontSize ?? FONT_SIZE.base,
      FALLBACK_VALUES.fontWeight.normal,
    );
    controlText.name = "Label";
    if (controlStyles.textVariable) {
      const textVar = getVariableByName(controlStyles.textVariable);
      if (textVar) {
        bindTextColorToVariable(controlText, textVar.id);
      }
    }
    control.appendChild(controlText);
    component.appendChild(control);
  }

  return component;
}

/**
 * Generate Toolbar ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateToolbarComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getToolbarSizeConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  let currentY = 0;
  for (const size of config.values) {
    const component = await createToolbarComponent(size);
    rowLabels.push({ y: currentY, text: "size=" + size });
    component.x = 160;
    component.y = currentY;
    currentY += component.height + 48;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "Toolbar";
  componentSet.description = "Grouped toolbar controls";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "Toolbar",
      startY,
      rowLabels,
      labelColumnWidth: 160,
    },
  );

  logComplete(
    "Generated Toolbar ComponentSet with " +
      components.length +
      " sizes (light + dark)",
  );

  return nextY;
}
