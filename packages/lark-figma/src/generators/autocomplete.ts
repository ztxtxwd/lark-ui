/**
 * Autocomplete Component Generator
 *
 * Generates an Autocomplete ComponentSet in Figma.
 *
 * Autocomplete is a text input with a filtered suggestion list. Its size
 * follows the Input component, and the suggestion list is Feishu's
 * `.ud__select__list` surface: a floating panel with a 6px radius, a card
 * border and the `--shadow-s4-down` elevation.
 *
 * @see packages/lark/src/components/autocomplete/autocomplete.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindFillToVariable,
  bindStrokeToVariable,
  bindTextColorToVariable,
  createShadowEffects,
  LARK_SHADOWS,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  SPACING,
  VAR_NAMES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { logComplete } from "../logger";

// Import variant data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

/**
 * The Autocomplete input follows the Input component, so the sizes are read
 * from the Input registry entry.
 */
const inputSizeProp = registry.components.Input.props.size as {
  values: string[];
  classes: Record<string, string>;
  descriptions: Record<string, string>;
  default: string;
};

/**
 * The input surface of the Autocomplete
 * (from LARK_INPUT_VARIANTS.variant.default)
 */
const INPUT_CLASSES =
  "bg-lark-base ring-lark-border hover:ring-lark-brand focus:ring-lark-brand";

/**
 * The suggestion list surface
 * (flex flex-col py-0.5 bg-lark-elevated text-lark-default rounded-md shadow-lark-popover ring ring-lark-line overflow-hidden)
 */
const POPUP_CLASSES =
  "flex flex-col py-0.5 bg-lark-elevated text-lark-default rounded-md shadow-lark-popover ring ring-lark-line overflow-hidden";

/**
 * A suggestion row
 * (group mx-[3px] my-px grid cursor-pointer grid-cols-[1fr_16px] gap-2 rounded px-2 py-1 text-base)
 */
const ITEM_CLASSES =
  "group mx-[3px] my-px grid cursor-pointer grid-cols-[1fr_16px] gap-2 rounded px-2 py-1 text-base";

/**
 * The highlighted suggestion row (data-highlighted:bg-lark-fill-hover)
 */
const ITEM_HIGHLIGHTED_CLASSES = "bg-lark-fill-hover";

/** Sample suggestions */
const SAMPLE_ITEMS = ["Apple", "Banana", "Cherry"];

/** Width of the generated autocomplete */
const AUTOCOMPLETE_WIDTH = 280;

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get size configuration (shared with the Input component)
 */
export function getAutocompleteSizeConfig() {
  return {
    values: inputSizeProp.values,
    classes: inputSizeProp.classes,
    descriptions: inputSizeProp.descriptions,
    default: inputSizeProp.default,
  };
}

/**
 * Get parsed base styles
 */
export function getAutocompleteParsedBaseStyles() {
  return parseTailwindClasses(INPUT_CLASSES);
}

/**
 * Get parsed styles for a specific size
 */
export function getAutocompleteParsedSizeStyles(size: string) {
  const classes = inputSizeProp.classes[size] || "";
  return {
    size,
    classes,
    description: inputSizeProp.descriptions[size] || "",
    parsed: parseTailwindClasses(classes),
  };
}

/**
 * Get all size data (for snapshot testing)
 */
export function getAllAutocompleteVariantData() {
  const baseStyles = getAutocompleteParsedBaseStyles();
  const popupStyles = parseTailwindClasses(POPUP_CLASSES);
  const itemStyles = parseTailwindClasses(ITEM_CLASSES);
  const config = getAutocompleteSizeConfig();

  return {
    baseStyles: {
      raw: INPUT_CLASSES,
      parsed: baseStyles,
    },
    popup: {
      raw: POPUP_CLASSES,
      parsed: popupStyles,
    },
    item: {
      raw: ITEM_CLASSES,
      parsed: itemStyles,
    },
    sizes: config.values.map((size) => {
      const sizeData = getAutocompleteParsedSizeStyles(size);
      return {
        ...sizeData,
        layout: {
          layoutMode: "VERTICAL",
          primaryAxisAlignItems: "MIN",
          counterAxisAlignItems: "MIN",
          itemSpacing: popupStyles.gap ?? 0,
          width: AUTOCOMPLETE_WIDTH,
          height: sizeData.parsed.height ?? 32,
          cornerRadius: sizeData.parsed.borderRadius ?? BORDER_RADIUS.md,
          fontSize: sizeData.parsed.fontSize ?? FONT_SIZE.base,
        },
      };
    }),
  };
}

/**
 * Create a single Autocomplete component
 */
async function createAutocompleteComponent(
  size: string,
): Promise<ComponentNode> {
  const baseStyles = getAutocompleteParsedBaseStyles();
  const popupStyles = parseTailwindClasses(POPUP_CLASSES);
  const itemStyles = parseTailwindClasses(ITEM_CLASSES);
  const sizeStyles = getAutocompleteParsedSizeStyles(size).parsed;

  const component = figma.createComponent();
  component.name = "size=" + size;
  component.description = inputSizeProp.descriptions[size] || "";

  component.layoutMode = "VERTICAL";
  component.primaryAxisAlignItems = "MIN";
  component.counterAxisAlignItems = "MIN";
  component.primaryAxisSizingMode = "AUTO";
  component.counterAxisSizingMode = "FIXED";
  component.itemSpacing = 0;
  component.paddingLeft = 0;
  component.paddingRight = 0;
  component.paddingTop = 0;
  component.paddingBottom = 0;
  component.fills = [];
  component.resize(AUTOCOMPLETE_WIDTH, 120);

  // Input
  const input = figma.createFrame();
  input.name = "Input";
  input.layoutMode = "HORIZONTAL";
  input.primaryAxisAlignItems = "CENTER";
  input.counterAxisAlignItems = "CENTER";
  input.primaryAxisSizingMode = "FIXED";
  input.counterAxisSizingMode = "FIXED";
  input.itemSpacing = sizeStyles.gap ?? SPACING.xs;
  input.paddingLeft = sizeStyles.paddingLeft ?? 11;
  input.paddingRight = sizeStyles.paddingRight ?? 8;
  input.paddingTop = 0;
  input.paddingBottom = 0;
  input.cornerRadius = sizeStyles.borderRadius ?? BORDER_RADIUS.md;
  input.resize(AUTOCOMPLETE_WIDTH, sizeStyles.height ?? 32);

  if (baseStyles.fillVariable) {
    const bgVar = getVariableByName(baseStyles.fillVariable);
    if (bgVar) {
      bindFillToVariable(input, bgVar.id);
    }
  }
  if (baseStyles.strokeVariable) {
    const borderVar = getVariableByName(baseStyles.strokeVariable);
    if (borderVar) {
      bindStrokeToVariable(input, borderVar.id, 1);
    }
  }

  const inputText = await createTextNode(
    "Search…",
    sizeStyles.fontSize ?? FONT_SIZE.base,
    FALLBACK_VALUES.fontWeight.normal,
  );
  inputText.name = "Placeholder";
  const placeholderVar = getVariableByName(VAR_NAMES.text.placeholder);
  if (placeholderVar) {
    bindTextColorToVariable(inputText, placeholderVar.id);
  }
  input.appendChild(inputText);
  component.appendChild(input);

  // Suggestion list
  const popup = figma.createFrame();
  popup.name = "List";
  popup.layoutMode = "VERTICAL";
  popup.primaryAxisAlignItems = "MIN";
  popup.counterAxisAlignItems = "MIN";
  popup.primaryAxisSizingMode = "AUTO";
  popup.counterAxisSizingMode = "FIXED";
  popup.itemSpacing = popupStyles.gap ?? 0;
  popup.paddingLeft = popupStyles.paddingX ?? 0;
  popup.paddingRight = popupStyles.paddingX ?? 0;
  popup.paddingTop = popupStyles.paddingY ?? 2;
  popup.paddingBottom = popupStyles.paddingY ?? 2;
  popup.cornerRadius = popupStyles.borderRadius ?? BORDER_RADIUS.md;

  if (popupStyles.fillVariable) {
    const popupBg = getVariableByName(popupStyles.fillVariable);
    if (popupBg) {
      bindFillToVariable(popup, popupBg.id);
    }
  }
  if (popupStyles.strokeVariable) {
    const popupBorder = getVariableByName(popupStyles.strokeVariable);
    if (popupBorder) {
      bindStrokeToVariable(popup, popupBorder.id, 1);
    }
  }
  popup.effects = createShadowEffects(LARK_SHADOWS.popover);

  for (let index = 0; index < SAMPLE_ITEMS.length; index++) {
    const item = figma.createFrame();
    item.name = "Item: " + SAMPLE_ITEMS[index];
    item.layoutMode = "HORIZONTAL";
    item.primaryAxisAlignItems = "MIN";
    item.counterAxisAlignItems = "CENTER";
    item.primaryAxisSizingMode = "FIXED";
    item.counterAxisSizingMode = "AUTO";
    item.itemSpacing = itemStyles.gap ?? SPACING.base;
    item.paddingLeft = itemStyles.paddingX ?? 8;
    item.paddingRight = itemStyles.paddingX ?? 8;
    item.paddingTop = itemStyles.paddingY ?? 4;
    item.paddingBottom = itemStyles.paddingY ?? 4;
    item.cornerRadius = itemStyles.borderRadius ?? BORDER_RADIUS.sm;

    // The first row is the highlighted one
    if (index === 0) {
      const highlightStyles = parseTailwindClasses(ITEM_HIGHLIGHTED_CLASSES);
      if (highlightStyles.fillVariable) {
        const highlightVar = getVariableByName(highlightStyles.fillVariable);
        if (highlightVar) {
          bindFillToVariable(item, highlightVar.id);
        }
      }
    } else {
      item.fills = [];
    }

    const itemText = await createTextNode(
      SAMPLE_ITEMS[index],
      itemStyles.fontSize ?? FONT_SIZE.base,
      FALLBACK_VALUES.fontWeight.normal,
    );
    itemText.name = "Label";
    const itemVar = getVariableByName(VAR_NAMES.text.default);
    if (itemVar) {
      bindTextColorToVariable(itemText, itemVar.id);
    }
    item.appendChild(itemText);

    popup.appendChild(item);
  }

  component.appendChild(popup);

  return component;
}

/**
 * Generate Autocomplete ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateAutocompleteComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getAutocompleteSizeConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  let currentY = 0;
  for (const size of config.values) {
    const component = await createAutocompleteComponent(size);
    rowLabels.push({ y: currentY, text: "size=" + size });
    component.x = 160;
    component.y = currentY;
    currentY += component.height + 48;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "Autocomplete";
  componentSet.description = "Text input with a filtered suggestion list";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "Autocomplete",
      startY,
      rowLabels,
      labelColumnWidth: 160,
    },
  );

  logComplete(
    "Generated Autocomplete ComponentSet with " +
      components.length +
      " sizes (light + dark)",
  );

  return nextY;
}
