/**
 * TagInput Component Generator
 *
 * Generates a TagInput ComponentSet in Figma.
 *
 * TagInput is Feishu's multi-value input: a wrapping field container that
 * holds neutral chips plus a text input. The container and chip styles come
 * from the TagInput styling metadata.
 *
 * @see packages/lark/src/components/tag-input/tag-input.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindFillToVariable,
  bindStrokeToVariable,
  bindTextColorToVariable,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  VAR_NAMES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { logComplete } from "../logger";

// Import variant data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

const tagInput = registry.components
  .TagInput as typeof registry.components.TagInput & {
  styling?: { baseClasses?: string; chipClasses?: string };
};

const variantProp = tagInput.props.variant as {
  values: string[];
  descriptions?: Record<string, string>;
  default?: string;
};

/** Field container classes (LARK_TAG_INPUT_STYLING.baseClasses) */
const BASE_CLASSES =
  tagInput.styling?.baseClasses ||
  "flex h-auto min-h-8 flex-wrap items-center gap-x-1 gap-y-0.5 px-[3px] py-1";

/** Neutral chip classes (LARK_TAG_INPUT_STYLING.chipClasses) */
const CHIP_CLASSES =
  tagInput.styling?.chipClasses ||
  "h-6 rounded-sm bg-lark-overlay pr-[3px] pl-2 text-sm";

/** Sample chip labels */
const SAMPLE_TAGS = ["Design", "Engineering"];

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get variant configuration from registry
 */
export function getTagInputVariantConfig() {
  return {
    values: variantProp.values,
    descriptions: variantProp.descriptions ?? {},
    default: variantProp.default ?? "default",
  };
}

/**
 * Get parsed base styles
 */
export function getTagInputParsedBaseStyles() {
  return parseTailwindClasses(BASE_CLASSES);
}

/**
 * Get parsed chip styles
 */
export function getTagInputParsedChipStyles() {
  return parseTailwindClasses(CHIP_CLASSES);
}

/**
 * Get all variant data (for snapshot testing)
 */
export function getAllTagInputVariantData() {
  const baseStyles = getTagInputParsedBaseStyles();
  const chipStyles = getTagInputParsedChipStyles();
  const config = getTagInputVariantConfig();

  return {
    baseStyles: {
      raw: BASE_CLASSES,
      parsed: baseStyles,
    },
    chipStyles: {
      raw: CHIP_CLASSES,
      parsed: chipStyles,
    },
    variants: config.values.map((variant) => ({
      variant,
      description: config.descriptions[variant] || "",
      layout: {
        layoutMode: "HORIZONTAL",
        primaryAxisAlignItems: "CENTER",
        counterAxisAlignItems: "CENTER",
        itemSpacing: baseStyles.gap ?? 4,
        paddingLeft: baseStyles.paddingX ?? 3,
        paddingRight: baseStyles.paddingX ?? 3,
        paddingTop: baseStyles.paddingY ?? 4,
        paddingBottom: baseStyles.paddingY ?? 4,
        cornerRadius: baseStyles.borderRadius ?? BORDER_RADIUS.md,
        primaryAxisSizingMode: "AUTO",
        counterAxisSizingMode: "AUTO",
      },
      chip: {
        height: chipStyles.height ?? 24,
        cornerRadius: chipStyles.borderRadius ?? BORDER_RADIUS.sm,
        fontSize: chipStyles.fontSize ?? FONT_SIZE.base,
      },
    })),
  };
}

/**
 * Create a single TagInput component
 */
async function createTagInputComponent(
  variant: string,
): Promise<ComponentNode> {
  const baseStyles = getTagInputParsedBaseStyles();
  const chipStyles = getTagInputParsedChipStyles();

  const component = figma.createComponent();
  component.name = "variant=" + variant;
  component.description = variantProp.descriptions?.[variant] || "";

  component.layoutMode = "HORIZONTAL";
  component.primaryAxisAlignItems = "CENTER";
  component.counterAxisAlignItems = "CENTER";
  component.primaryAxisSizingMode = "AUTO";
  component.counterAxisSizingMode = "AUTO";
  component.itemSpacing = baseStyles.gapX ?? baseStyles.gap ?? 4;
  component.paddingLeft = baseStyles.paddingX ?? 3;
  component.paddingRight = baseStyles.paddingX ?? 3;
  component.paddingTop = baseStyles.paddingY ?? 4;
  component.paddingBottom = baseStyles.paddingY ?? 4;
  component.cornerRadius = baseStyles.borderRadius ?? BORDER_RADIUS.md;

  // The field container uses the page background
  const bgVar = getVariableByName(VAR_NAMES.color.base);
  if (bgVar) {
    bindFillToVariable(component, bgVar.id);
  }

  // Feishu outlines the field with the component border colour
  const borderVar = getVariableByName(VAR_NAMES.color.border);
  if (borderVar) {
    bindStrokeToVariable(component, borderVar.id, 1);
  }

  // Chips
  for (const tag of SAMPLE_TAGS) {
    const chip = figma.createFrame();
    chip.name = "Chip: " + tag;
    chip.layoutMode = "HORIZONTAL";
    chip.primaryAxisAlignItems = "CENTER";
    chip.counterAxisAlignItems = "CENTER";
    chip.primaryAxisSizingMode = "AUTO";
    chip.counterAxisSizingMode = "AUTO";
    chip.paddingLeft = chipStyles.paddingLeft ?? 8;
    chip.paddingRight = chipStyles.paddingRight ?? 3;
    chip.paddingTop = 0;
    chip.paddingBottom = 0;
    chip.cornerRadius = chipStyles.borderRadius ?? BORDER_RADIUS.sm;

    if (chipStyles.fillVariable) {
      const chipBg = getVariableByName(chipStyles.fillVariable);
      if (chipBg) {
        bindFillToVariable(chip, chipBg.id);
      }
    }

    const chipText = await createTextNode(
      tag,
      chipStyles.fontSize ?? FONT_SIZE.base,
      FALLBACK_VALUES.fontWeight.normal,
    );
    chipText.name = "Label";
    if (chipStyles.textVariable) {
      const chipTextVar = getVariableByName(chipStyles.textVariable);
      if (chipTextVar) {
        bindTextColorToVariable(chipText, chipTextVar.id);
      }
    }
    chip.appendChild(chipText);
    component.appendChild(chip);
  }

  return component;
}

/**
 * Generate TagInput ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateTagInputComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getTagInputVariantConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  let currentY = 0;
  for (const variant of config.values) {
    const component = await createTagInputComponent(variant);
    rowLabels.push({ y: currentY, text: "variant=" + variant });
    component.x = 160;
    component.y = currentY;
    currentY += component.height + 48;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "TagInput";
  componentSet.description = "Multi-value input with neutral chips";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "TagInput",
      startY,
      rowLabels,
      labelColumnWidth: 160,
    },
  );

  logComplete(
    "Generated TagInput ComponentSet with " +
      components.length +
      " variants (light + dark)",
  );

  return nextY;
}
