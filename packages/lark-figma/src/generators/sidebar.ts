/**
 * Sidebar Component Generator
 *
 * Generates a Sidebar ComponentSet in Figma.
 *
 * The sidebar is the app navigation rail. Feishu offers three variants —
 * `sidebar` (separated by a border), `floating` (a detached card) and
 * `inset` (nested in the content area). The widths come from the Sidebar
 * styling metadata in the registry.
 *
 * @see packages/lark/src/components/sidebar/sidebar.tsx
 */

import {
  createTextNode,
  getVariableByName,
  bindFillToVariable,
  bindStrokeToVariable,
  bindTextColorToVariable,
  createShadowEffects,
  LARK_SHADOWS,
  BORDER_RADIUS,
  FONT_SIZE,
  FALLBACK_VALUES,
  SPACING,
  VAR_NAMES,
  placeComponentSetSections,
} from "./shared";
import { parseTailwindClasses } from "../parsers/tailwind-to-figma";
import { createIconInstance, bindIconColor } from "./icon-utils";
import { logComplete } from "../logger";

// Import styling data from the registry (generated by build:ai-metadata)
import registry from "@lark-ui/core/ai/component-registry.json";

const sidebarComponent = registry.components
  .Sidebar as typeof registry.components.Sidebar & {
  styling?: {
    width?: { expanded?: string; icon?: string };
  };
};

const variantProp = sidebarComponent.props.variant as {
  values: string[];
  descriptions?: Record<string, string>;
  default?: string;
};

/**
 * Surface classes per variant.
 * - `sidebar` is separated from the content by a border
 * - `floating` is a detached card with Feishu's large elevation
 * - `inset` sits on the recessed background
 */
const VARIANT_CLASSES: Record<string, string> = {
  sidebar: "border-r border-lark-line bg-lark-base",
  floating: "m-2 rounded-lg border border-lark-line bg-lark-base",
  inset: "bg-lark-base",
};

/**
 * Sidebar header
 * (flex h-[58px] shrink-0 items-center gap-1 border-b border-lark-line)
 */
const HEADER_CLASSES =
  "flex h-[58px] shrink-0 items-center gap-1 border-b border-lark-line";

/**
 * Menu area
 * (flex min-h-0 w-full flex-1 flex-col gap-4 px-2 py-3)
 */
const MENU_CLASSES = "flex min-h-0 w-full flex-1 flex-col gap-4 px-2 py-3";

/**
 * Menu button
 * (group/menu-button relative flex w-full min-w-0 cursor-pointer items-center gap-2.5 rounded-lg outline-none min-h-8.5 px-3 py-0 text-sm font-medium text-lark-default)
 */
const MENU_ITEM_CLASSES =
  "group/menu-button relative flex w-full min-w-0 cursor-pointer items-center gap-2.5 rounded-lg outline-none min-h-8.5 px-3 py-0 text-sm font-medium text-lark-default";

/** Sample navigation entries */
const SAMPLE_ITEMS = [
  { label: "Home", icon: "ph-house" },
  { label: "Documents", icon: "ph-file-text" },
  { label: "Settings", icon: "ph-gear" },
];

/** Menu icon size */
const MENU_ICON_SIZE = 16;

/**
 * Convert a CSS length (`16.25rem`, `57px`) to pixels.
 */
function toPixels(value: string | undefined, fallback: number): number {
  if (!value) return fallback;
  const remMatch = value.match(/^([\d.]+)rem$/);
  if (remMatch) return parseFloat(remMatch[1]) * 16;
  const pxMatch = value.match(/^([\d.]+)px$/);
  if (pxMatch) return parseFloat(pxMatch[1]);
  return fallback;
}

/**
 * TESTABLE EXPORTS - Pure functions that return intermediate data
 */

/**
 * Get variant configuration
 */
export function getSidebarVariantConfig() {
  return {
    values: variantProp.values,
    classes: VARIANT_CLASSES,
    descriptions: variantProp.descriptions ?? {},
    default: variantProp.default ?? "sidebar",
  };
}

/**
 * Get the expanded width in pixels (from the registry styling metadata)
 */
export function getSidebarWidth(): number {
  return toPixels(sidebarComponent.styling?.width?.expanded, 260);
}

/**
 * Get the collapsed (icon only) width in pixels
 */
export function getSidebarIconWidth(): number {
  return toPixels(sidebarComponent.styling?.width?.icon, 57);
}

/**
 * Get parsed styles for a specific variant
 */
export function getSidebarParsedVariantStyles(variant: string) {
  const classes = VARIANT_CLASSES[variant] || "";
  return {
    variant,
    classes,
    parsed: parseTailwindClasses(classes),
  };
}

/**
 * Get all variant data (for snapshot testing)
 */
export function getAllSidebarVariantData() {
  const headerStyles = parseTailwindClasses(HEADER_CLASSES);
  const menuStyles = parseTailwindClasses(MENU_CLASSES);
  const itemStyles = parseTailwindClasses(MENU_ITEM_CLASSES);
  const config = getSidebarVariantConfig();

  return {
    header: {
      raw: HEADER_CLASSES,
      parsed: headerStyles,
    },
    menu: {
      raw: MENU_CLASSES,
      parsed: menuStyles,
    },
    item: {
      raw: MENU_ITEM_CLASSES,
      parsed: itemStyles,
    },
    width: {
      expanded: getSidebarWidth(),
      icon: getSidebarIconWidth(),
    },
    variants: config.values.map((variant) => {
      const variantData = getSidebarParsedVariantStyles(variant);
      return {
        ...variantData,
        layout: {
          layoutMode: "VERTICAL",
          primaryAxisAlignItems: "MIN",
          counterAxisAlignItems: "MIN",
          width: getSidebarWidth(),
          itemSpacing: menuStyles.gap ?? 16,
          paddingLeft: menuStyles.paddingX ?? 8,
          paddingRight: menuStyles.paddingX ?? 8,
          paddingTop: menuStyles.paddingY ?? 12,
          paddingBottom: menuStyles.paddingY ?? 12,
          cornerRadius: variantData.parsed.borderRadius ?? BORDER_RADIUS.lg,
        },
      };
    }),
  };
}

/**
 * Create a single Sidebar component
 */
async function createSidebarComponent(variant: string): Promise<ComponentNode> {
  const headerStyles = parseTailwindClasses(HEADER_CLASSES);
  const menuStyles = parseTailwindClasses(MENU_CLASSES);
  const itemStyles = parseTailwindClasses(MENU_ITEM_CLASSES);
  const variantStyles = getSidebarParsedVariantStyles(variant).parsed;

  const component = figma.createComponent();
  component.name = "variant=" + variant;
  component.description = variantProp.descriptions?.[variant] || "";

  component.layoutMode = "VERTICAL";
  component.primaryAxisAlignItems = "MIN";
  component.counterAxisAlignItems = "MIN";
  component.primaryAxisSizingMode = "FIXED";
  component.counterAxisSizingMode = "FIXED";
  component.itemSpacing = 0;
  component.paddingLeft = 0;
  component.paddingRight = 0;
  component.paddingTop = 0;
  component.paddingBottom = 0;
  component.cornerRadius = variantStyles.borderRadius ?? 0;
  component.resize(getSidebarWidth(), 480);

  // Surface
  if (variantStyles.fillVariable) {
    const bgVar = getVariableByName(variantStyles.fillVariable);
    if (bgVar) {
      bindFillToVariable(component, bgVar.id);
    }
  }

  // Border
  if (variantStyles.strokeVariable) {
    const borderVar = getVariableByName(variantStyles.strokeVariable);
    if (borderVar) {
      bindStrokeToVariable(component, borderVar.id, 1);
    }
  }

  // The floating variant is a detached card with Feishu's large elevation
  if (variant === "floating") {
    component.effects = createShadowEffects(LARK_SHADOWS.lg);
  }

  // Header
  const header = figma.createFrame();
  header.name = "Header";
  header.layoutMode = "HORIZONTAL";
  header.primaryAxisAlignItems = "CENTER";
  header.counterAxisAlignItems = "CENTER";
  header.primaryAxisSizingMode = "FIXED";
  header.counterAxisSizingMode = "FIXED";
  header.itemSpacing = SPACING.xs;
  header.paddingLeft = SPACING.base;
  header.paddingRight = SPACING.base;
  header.paddingTop = 0;
  header.paddingBottom = 0;
  header.resize(getSidebarWidth(), headerStyles.height ?? 58);
  header.fills = [];

  const headerText = await createTextNode(
    "Workspace",
    FONT_SIZE.base,
    FALLBACK_VALUES.fontWeight.semiBold,
  );
  headerText.name = "Title";
  const headerVar = getVariableByName(VAR_NAMES.text.default);
  if (headerVar) {
    bindTextColorToVariable(headerText, headerVar.id);
  }
  header.appendChild(headerText);
  component.appendChild(header);

  // Menu
  const menu = figma.createFrame();
  menu.name = "Menu";
  menu.layoutMode = "VERTICAL";
  menu.primaryAxisAlignItems = "MIN";
  menu.counterAxisAlignItems = "MIN";
  menu.primaryAxisSizingMode = "AUTO";
  menu.counterAxisSizingMode = "FIXED";
  menu.itemSpacing = menuStyles.gap ?? SPACING.base;
  menu.paddingLeft = menuStyles.paddingX ?? SPACING.base;
  menu.paddingRight = menuStyles.paddingX ?? SPACING.base;
  menu.paddingTop = menuStyles.paddingY ?? 12;
  menu.paddingBottom = menuStyles.paddingY ?? 12;
  menu.fills = [];

  for (const entry of SAMPLE_ITEMS) {
    const item = figma.createFrame();
    item.name = "Item: " + entry.label;
    item.layoutMode = "HORIZONTAL";
    item.primaryAxisAlignItems = "MIN";
    item.counterAxisAlignItems = "CENTER";
    item.primaryAxisSizingMode = "FIXED";
    item.counterAxisSizingMode = "AUTO";
    item.itemSpacing = itemStyles.gap ?? 10;
    item.paddingLeft = itemStyles.paddingX ?? 12;
    item.paddingRight = itemStyles.paddingX ?? 12;
    item.paddingTop = 0;
    item.paddingBottom = 0;
    item.cornerRadius = itemStyles.borderRadius ?? BORDER_RADIUS.lg;
    item.fills = [];

    const icon = createIconInstance(entry.icon, MENU_ICON_SIZE);
    if (icon) {
      icon.name = "Icon";
      if (itemStyles.textVariable) {
        bindIconColor(icon, itemStyles.textVariable);
      }
      item.appendChild(icon);
    }

    const label = await createTextNode(
      entry.label,
      itemStyles.fontSize ?? FONT_SIZE.base,
      itemStyles.fontWeight ?? FALLBACK_VALUES.fontWeight.medium,
    );
    label.name = "Label";
    if (itemStyles.textVariable) {
      const labelVar = getVariableByName(itemStyles.textVariable);
      if (labelVar) {
        bindTextColorToVariable(label, labelVar.id);
      }
    }
    item.appendChild(label);

    menu.appendChild(item);
  }

  component.appendChild(menu);

  return component;
}

/**
 * Generate Sidebar ComponentSet
 *
 * @param startY - Y position to start placing the section
 * @returns The Y position after this section (for next section placement)
 */
export async function generateSidebarComponents(
  startY: number,
): Promise<number> {
  if (startY === undefined) startY = 100;

  const config = getSidebarVariantConfig();
  const components: ComponentNode[] = [];
  const rowLabels: { y: number; text: string }[] = [];

  let currentY = 0;
  for (const variant of config.values) {
    const component = await createSidebarComponent(variant);
    rowLabels.push({ y: currentY, text: "variant=" + variant });
    component.x = 160;
    component.y = currentY;
    currentY += component.height + 48;
    components.push(component);
  }

  // @ts-ignore - combineAsVariants works at runtime
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = "Sidebar";
  componentSet.description = "Application navigation rail";

  const nextY = await placeComponentSetSections(
    figma.currentPage,
    componentSet,
    components,
    {
      name: "Sidebar",
      startY,
      rowLabels,
      labelColumnWidth: 160,
    },
  );

  logComplete(
    "Generated Sidebar ComponentSet with " +
      components.length +
      " variants (light + dark)",
  );

  return nextY;
}
